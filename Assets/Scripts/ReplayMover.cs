using System;
using UnityEngine;

namespace DefaultNamespace
{
	[RequireComponent(typeof(PositionSaver))]
	public class ReplayMover : MonoBehaviour
	{
		private PositionSaver _save;

		private int _index;
		private PositionSaver.Data _prev;
		private float _duration;

		private void Start()
		{

            // todo comment: Зачем нужны эти проверки?
            // Это защита от невалидного состояния. TryGetComponent безопасно проверяет наличие компонента
			// (в отличие от GetComponent, который просто вернёт null).
			// Records.Count == 0 — случай, когда запись не велась или список пуст: двигаться не по чему.
			// Без этих проверок Update упал бы с NullReferenceException или IndexOutOfRangeException на первом же кадре.

            if (!TryGetComponent(out _save) || _save.Records.Count == 0)
			{
				Debug.LogError("Records incorrect value", this);

                // todo comment: Для чего выключается этот компонент?
                // Для того, чтобы остановить воспроизведение, которое невозможно выполнить.
				// Пока компонент включён, Unity каждый кадр вызывает Update —
				// и каждый кадр код падал бы на невалидных данных.
				// Отключение прерывает этот цикл, а вместо бесконечного потока ошибок в консоль один раз пишется лог.

                enabled = false;
			}
		}

		private void Update()
		{
			var curr = _save.Records[_index];

            // todo comment: Что проверяет это условие (с какой целью)?
            // Это проверка того, дошло ли время воспроизведения до следующей записанной точки.
			// У каждой записи есть временная метка. Когда игровое время перевалило за метку curr,
			// значит точка пройдена, и её надо зафиксировать как предыдущую (_prev = curr),
			// а взгляд переключить на следующую запись.
			// Цель состоит в том, чтобы синхронизировать воспроизведение с темпом, в котором велась запись,
			// то есть объект двигается по точкам ровно в те же игровые моменты, в которые они записывались.

            if (Time.time > curr.Time)
			{
				_prev = curr;
				_index++;

                // todo comment: Для чего нужна эта проверка?
                // Это условие конца воспроизведения. После инкремента _index может указывать за пределы списка.
				// Без проверки следующий Update обратился бы к Records[_index] и упал с IndexOutOfRangeException.
				// Если индекс дошёл до конца — все точки проиграны, а компонент выключается и пишет «finished».

                if (_index >= _save.Records.Count)
				{
					enabled = false;
					Debug.Log($"<b>{name}</b> finished", this);
				}
			}

            // todo comment: Для чего производятся эти вычисления (как в дальнейшем они применяются)?
            // Здесь считается коэффициент интерполяции delta, то есть доля пути между двумя точками.
            // Когда Time.time равен _prev.Time, delta = 0 (мы в предыдущей точке);
			// когда дошло до curr.Time — delta = 1 (мы в следующей точке).
			// Всё, что между ними — плавный переход. Дальше этот коэффициент передаётся в Vector3.Lerp,
			// чтобы получить промежуточную позицию.
			// Формула к.и. превращает набор дискретных записей в плавное движение, повторяющее исходный темп.

            var delta = (Time.time - _prev.Time) / (curr.Time - _prev.Time);

            // todo comment: Зачем нужна эта проверка?
            // При делении знаменатель curr.Time - _prev.Time может оказаться нулём —
			// например, две записи с одинаковой временной меткой (записали в один кадр, или deltaTime очень маленький).
			// Деление нуля на ноль даёт NaN. Если передать NaN в Vector3.Lerp, на выходе получится позиция из NaN —
			// объект исчезнет из мира, а в консоли появятся ошибки о некорректной трансформации.
			// Замена на 0f — безопасный fallback. По сути объект просто останется на предыдущей точке.

            if (float.IsNaN(delta)) delta = 0f;

            // todo comment: Опишите, что происходит в этой строчке так подробно, насколько это возможно.
            // Статический метод Vector3.Lerp(a, b, t) выполняет линейную интерполяцию.
			// Он принимает две позиции a и b и коэффициент t. При t = 0 возвращает a, при t = 1 — b,
			// а при промежуточных значениях — точку на прямом отрезке между ними: a + (b - a) * t.
			// Например, при t = 0.25 — четверть пути от a к b.
			// В этой строке в качестве a берётся позиция предыдущей записи _prev.Position, в качестве b —
			// позиция текущей записи curr.Position, а коэффициентом служит вычисленный выше delta.
			// Результат присваивается позиции самого объекта —
			// то есть на каждом кадре кубик оказывается ровно в той точке отрезка между двумя записями,
			// которая соответствует текущему игровому времени.
			// Так набор дискретных мгновенных снимков превращается в непрерывное плавное движение,
			// повторяющее траекторию, которую мы рисовали мышью в режиме записи.

            transform.position = Vector3.Lerp(_prev.Position, curr.Position, delta);
		}
	}
}